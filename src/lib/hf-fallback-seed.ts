import type { HFModelSummary, ModelFormat } from "@/types/inference";

const SEED_TS = "2026-11-26T00:00:00.000Z";
const GIB = 1024 * 1024 * 1024;

function makeSeed(input: {
  id: string;
  pipelineTag?: string;
  libraryName?: string;
  formats: ModelFormat[];
  parametersB: number;
  activeParametersB?: number;
  isMoE?: boolean;
  architectureHint: string;
  defaultContextLength: number;
  downloads: number;
  likes: number;
  gated?: boolean;
  tags?: string[];
  embeddedConfig?: HFModelSummary["embeddedConfig"];
}): HFModelSummary {
  const [author, ...rest] = input.id.split("/");
  const name = rest.length > 0 ? rest.join("/") : input.id;
  const activeParametersB = input.activeParametersB ?? input.parametersB;
  const estFP16 = Number(((input.parametersB * 1e9 * 2) / GIB).toFixed(2));
  const estQ4 = Number(((input.parametersB * 1e9 * (4.85 / 8)) / GIB).toFixed(2));

  return {
    id: input.id,
    author: rest.length > 0 ? author : "huggingface",
    name,
    pipelineTag: input.pipelineTag ?? "text-generation",
    libraryName:
      input.libraryName ??
      (input.formats[0] === "gguf"
        ? "gguf"
        : input.formats[0] === "mlx"
          ? "mlx"
          : "transformers"),
    formats: input.formats,
    primaryFormat: input.formats[0],
    parametersB: input.parametersB,
    activeParametersB,
    isMoE: Boolean(input.isMoE),
    architectureHint: input.architectureHint,
    defaultContextLength: input.defaultContextLength,
    downloads: input.downloads,
    likes: input.likes,
    gated: Boolean(input.gated),
    lastModified: SEED_TS,
    tags: input.tags ?? [input.architectureHint.toLowerCase(), ...input.formats],
    estimatedDiskGBAtFP16: estFP16,
    estimatedDiskGBAtQ4: estQ4,
    embeddedConfig: input.embeddedConfig,
  };
}

