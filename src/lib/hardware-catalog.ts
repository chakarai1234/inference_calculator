export function getDeviceById(id: string): HardwareDevice {
  return (
    HARDWARE_CATALOG.find((d) => d.id === id) ??
    HARDWARE_CATALOG.find((d) => d.id === "apple-m4-max-64") ??
    HARDWARE_CATALOG[0]
  );
}

export function getEffectiveMemoryGB(
  device: HardwareDevice,
  gpuCount: number,
  appleWiredRatio: number
): number {
  const effectiveCount = device.supportsMultiGpu
    ? Math.max(1, Math.min(gpuCount, device.maxGpuCount))
    : 1;
  const ratio =
    device.vendor === "apple"
      ? Math.min(Math.max(appleWiredRatio, 0.5), device.maxUsableRatio)
      : device.defaultUsableRatio;
  return device.vramGB * effectiveCount * ratio;
}

export function getHardwareGroupedByVendor(): {
  label: string;
  devices: HardwareDevice[];
}[] {
  const groups = new Map<string, HardwareDevice[]>();
  for (const d of HARDWARE_CATALOG) {
    const existing = groups.get(d.vendorLabel) ?? [];
    existing.push(d);
    groups.set(d.vendorLabel, existing);
  }
  return Array.from(groups.entries()).map(([label, devices]) => ({
    label,
    devices,
  }));
}
